import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const box={};vm.runInNewContext(fs.readFileSync(new URL('../web/ctf-rules.js',import.meta.url),'utf8'),{window:box,Math,Number,Array,Error,RangeError});
const api=box.SectorFlags,bays=[{team:0,x:100,y:100},{team:1,x:700,y:100}];
const near=(team,x,y,onFoot=true,canCarry=true,alive=true)=>({team,x,y,onFoot,canCarry,alive});
const a0=(x,y,foot=true)=>near(0,x,y,foot);
const a1=(x,y,foot=true)=>near(1,x,y,foot);
const p=arr=>arr;
let s=api.create(bays);
assert.deepEqual([...s.scores],[0,0]);assert.equal(s.flags.length,2);
assert.equal(api.tick(s,p([a0(700,100,false)]),1).flags[1].carrier,null,'vehicles cannot take flags');
s=api.tick(s,p([a0(700,100)]),1);assert.equal(s.flags[1].carrier,0);
assert.equal(s.event.kind,'picked');
assert.equal(api.tick(s,p([a0(100,100,false)]),1).scores[0],0,'boarding cannot score');
const disembark=api.drop(s,0,700,100);
assert.equal(disembark.flags[1].carrier,null);
assert.ok(disembark.flags[1].droppedFor>0);
assert.equal(api.drop(disembark,0,700,100),disembark,'second drop is idempotent');
assert.equal(api.tick(disembark,p([a1(700,100)]),1).flags[1].droppedFor,0,'friendly touch returns flag');
let timeout=api.tick(api.tick(disembark,p([]),10),p([]),10);
assert.equal(timeout.flags[1].droppedFor,0,'drop returns after timer');
assert.equal(timeout.flags[1].x,700);
const forbidden=api.tick(api.create(bays),p([a0(700,100,true,false)]),1);
assert.equal(forbidden.flags[1].carrier,null,'bots without carry ability cannot grab flag');
const stolen=api.tick(api.create(bays),p([a0(700,100),a1(100,100)]),1);
assert.equal(stolen.flags[1].carrier,0);assert.equal(stolen.flags[0].carrier,1);
assert.deepEqual([...api.tick(stolen,p([a0(100,100),a1(700,100)]),1).scores],[0,0],
 'no capture while home flag is stolen');
let a=api.create(bays);
for(let n=1;n<=3;n++){
 a=api.tick(a,p([a0(700,100)]),1);
 a=api.tick(a,p([a0(100,100)]),1);
 assert.equal(a.scores[0],n);
 assert.equal(a.flags[1].carrier,null);
}
assert.equal(a.finished,true);assert.equal(a.winner,0);assert.equal(a.reason,'capture_target');
assert.equal(api.tick(a,p([a0(700,100)]),1),a,'finished rounds are frozen');
let tied=api.create(bays);
for(let n=0;n<36;n++)tied=api.tick(tied,[],10);
assert.equal(tied.finished,true);assert.equal(tied.winner,null);assert.equal(tied.reason,'time_limit');
let lead=api.create(bays);
lead=api.tick(lead,p([a0(700,100)]),1);
lead=api.tick(lead,p([a0(100,100)]),1);
for(let n=0;n<36;n++)lead=api.tick(lead,[],10);
assert.equal(lead.winner,0);assert.deepEqual([...lead.scores],[1,0]);
let death=api.tick(api.create(bays),p([a0(700,100)]),1);
death=api.tick(death,p([a0(690,95,true,true,false)]),1);
assert.equal(death.flags[1].carrier,null,'death drops held flag');
let returnFlag=api.tick(api.create(bays),p([a0(700,100)]),1);
returnFlag=api.drop(returnFlag,0,685,100);
returnFlag=api.tick(returnFlag,p([a1(685,100)]),.5);
assert.equal(returnFlag.flags[1].droppedFor,0);
assert.throws(()=>api.create([{team:0,x:NaN,y:0}]),/valid/);
assert.throws(()=>api.tick(api.create(bays),[],Infinity),/tick/);
console.log('CTF_RULES_CONTRACT_PASS: on-foot grab, vehicle rejection/drop, same-team return, timed return, home-flag capture gate, first-to-three, timeout/draw, idempotent terminal');
