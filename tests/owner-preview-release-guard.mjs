// Read-only guards. No real keystore/secret values accessed.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const gradle=fs.readFileSync('android/app/build.gradle','utf8');
const wf=fs.readFileSync('.github/workflows/owner-pinned-test-apk.yml','utf8');
const qa=fs.readFileSync('.github/workflows/build-apk.yml','utf8');
assert.match(gradle,/defaultPreviewVersionCode = 50/);
assert.match(gradle,/defaultPreviewVersionName = '0\.9\.54-lan-timeout-test'/);
assert.match(gradle,/Private TEST signer required for preview version overrides/);
assert.match(gradle,/requestedNumber <= defaultPreviewVersionCode/);
assert.match(gradle,/versionCode previewVersionCode/);
assert.match(gradle,/versionName previewVersionName/);
assert.match(gradle,/srPreviewPackage must be true when present/);
assert.match(gradle,/Preview versions require isolated \.preview app identity/);
assert.match(gradle,/applicationIdSuffix '\.preview'/);
assert.ok(wf.includes('workflow_dispatch:'));
assert.ok(!/^\s*push:/m.test(wf)&&!/^\s*pull_request:/m.test(wf));
assert.ok(wf.includes("github.ref == 'refs/heads/main'"),'private signing restricted to reviewed default branch');
for(const f of ['reviewed_source_sha','owner_approved','create_draft_release'])assert.ok(wf.includes(f));
assert.ok(wf.includes('"$REVIEWED_SHA" == "$GITHUB_SHA"'));
assert.ok(wf.includes('GITHUB_RUN_ATTEMPT'));
assert.ok(wf.includes('100000 + GITHUB_RUN_NUMBER'));
assert.ok(wf.includes('SR_TEST_CERT_SHA256'));
assert.ok(wf.includes('-PsrPreviewPackage=true'));
assert.ok(wf.includes('-PsrPreviewVersionCode=$PREVIEW_CODE'));
assert.ok(wf.includes('-PsrPreviewVersionName=$PREVIEW_NAME'));
assert.ok(wf.includes("com.playereden.ricochetrumble.preview"));
assert.ok(wf.includes('CERTIFICATE MISMATCH: BLOCK PREVIEW DISTRIBUTION'));
assert.ok(wf.includes('secrets.SR_TEST_KEYSTORE_B64'));
assert.ok(wf.includes('Erase temporary keystore on runner'));
assert.ok(wf.includes('--draft --prerelease'),'publishing never automatic; only draft is permitted');
assert.ok(wf.includes('inputs.create_draft_release == true'));
assert.ok(wf.includes('! gh release view'),'no overwriting a previous preview release');
assert.ok(wf.includes('sha256sum --check'));
const head=wf.split('    steps:')[0];
assert.ok(!head.includes('secrets.'),'no global inherited secret env');
assert.match(qa,/PREVIEW_CI_COMPATIBILITY_PASS/);
assert.match(qa,/cmp "\$TEST_DIR\/digest-100001.txt" "\$TEST_DIR\/digest-100002.txt"/);
assert.ok(!qa.includes('gh release create'));
console.log('PASS preview signing: isolated package, automatic codes, main-only secret access, owner consent, pinned signer, artifact verification, optional unpublished draft release, ephemeral two-version CI.');
