import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={};
vm.runInNewContext(fs.readFileSync(new URL('../web/lan-series.js',import.meta.url),'utf8'),context);
const s=context.SectorLanSeries;
assert.ok(s,'LAN series coordinator exported');
const first=s.createSeries();
assert.equal(s.valid(first,{finished:false}),true);
assert.equal(first.round,1);
assert.deepEqual([...first.wins],[0,0]);
assert.equal(s.nextRound(first),null,'no next round before result');
assert.equal(s.awardRound(first,{matchId:4,winningSide:7}),first,'invalid side rejected');
const r1=s.awardRound(first,{matchId:4,winningSide:1});
assert.equal(s.valid(r1,{matchId:4,finished:true}),true);
assert.deepEqual([...r1.wins],[0,1]);
assert.equal(r1.concluded,false);
assert.equal(s.awardRound(r1,{matchId:4,winningSide:1}),r1,'duplicate same match cannot re-award');
const r2=s.nextRound(r1);
assert.equal(r2.round,2);
assert.equal(r2.completedMatchId,null);
assert.deepEqual([...r2.wins],[0,1]);
assert.equal(s.valid(r2,{finished:false}),true);
assert.equal(s.valid(r2,{finished:true}),false,'guest must reject finished game with unawarded series');
const r2Final=s.awardRound(r2,{matchId:5,winningSide:1});
assert.equal(r2Final.concluded,true,'two wins clinch immediately');
assert.equal(r2Final.winner,1);
assert.equal(s.nextRound(r2Final),null,'no unwanted fourth game');
let tied=s.awardRound(s.nextRound(r1),{matchId:6,winningSide:0});
assert.deepEqual([...tied.wins],[1,1]);
const third=s.nextRound(tied);
assert.equal(third.round,3);
const final=s.awardRound(third,{matchId:7,winningSide:0});
assert.equal(final.concluded,true);
assert.equal(final.winner,0);
const draw1=s.awardRound(first,{matchId:8,winningSide:null});
const draw2=s.awardRound(s.nextRound(draw1),{matchId:9,winningSide:null});
const draw3=s.awardRound(s.nextRound(draw2),{matchId:10,winningSide:null});
assert.equal(draw3.concluded,true);
assert.equal(draw3.winner,null,'three draws make series draw');
assert.equal(s.valid({...draw3,wins:[1,1,1]}),false,'malformed wins rejected');
assert.equal(s.valid({...r1,completedMatchId:99},{matchId:4,finished:true}),false,'wrong-match award rejected');
assert.equal(s.valid({...r2,concluded:true}),false,'cannot conclude between rounds');
assert.throws(()=>s.createSeries(2),RangeError);
console.log('PASS D2 series kernel: win, clinch, 1-1 decider, draws, replay protection and strict guest validation');
