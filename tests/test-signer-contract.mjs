import fs from 'node:fs';
import assert from 'node:assert/strict';
const gradle=fs.readFileSync('android/app/build.gradle','utf8');
const workflow=fs.readFileSync('.github/workflows/owner-pinned-test-apk.yml','utf8');
assert.match(gradle,/versionCode 45/);
assert.match(gradle,/versionName '0\.9\.45-pilot-silhouette-test'/);
assert.match(gradle,/applicationId 'com\.playereden\.ricochetrumble'/);
for(const key of ['SR_TEST_STORE_FILE','SR_TEST_STORE_PASSWORD','SR_TEST_KEY_ALIAS','SR_TEST_KEY_PASSWORD'])assert.ok(gradle.includes(key));
assert.ok(gradle.includes("throw new GradleException('Incomplete private TEST APK signing configuration')"));
assert.ok(gradle.includes("throw new GradleException('Private TEST keystore file was not found')"));
assert.ok(gradle.includes('if (hasTestSigning) signingConfig signingConfigs.internalTest'));
assert.ok(gradle.includes('if (hasUploadSigning) signingConfig signingConfigs.releaseUpload'));
assert.ok(!/debug\s*\{[^}]*signingConfigs\.releaseUpload/s.test(gradle),'do not reuse Play upload key as test debug signer');
assert.ok(workflow.includes('workflow_dispatch:'),'only authorized manual dispatch may request private test signer');
assert.ok(!/pull_request:/.test(workflow),'never expose secrets to PRs');
assert.ok(!/\n\s+push:/.test(workflow),'no automatic secret use on push');
assert.ok(workflow.includes("CERTIFICATE MISMATCH: refusing to distribute test APK"));
assert.ok(workflow.includes('SR_TEST_CERT_SHA256'));
assert.ok(workflow.includes('base64 --decode'));
assert.ok(workflow.includes('Erase temporary keystore from CI runner'));
const head=workflow.split('    steps:')[0];
assert.ok(!head.includes('secrets.'),'private keys never inherited by all job steps');
for(const secret of ['SR_TEST_STORE_PASSWORD','SR_TEST_KEY_ALIAS','SR_TEST_KEY_PASSWORD','SR_TEST_KEYSTORE_B64'])assert.ok(workflow.includes('secrets.'+secret));
assert.ok(!workflow.includes('gh release create'),'signed test workflow must not auto-publish an APK');
console.log('PASS v0.9.43 private manually triggered test signer: complete external env, no PR/push secret exposure, separate production key, pinned cert and no automatic publish.');
