import assert from 'node:assert/strict';
import fs from 'node:fs';
const workflow=fs.readFileSync('.github/workflows/automatic-preview-apk.yml','utf8');
const gradle=fs.readFileSync('android/app/build.gradle','utf8');
assert.match(workflow,/on:\n  push:/,'automatic builds should run on reviewed integration pushes');
assert.match(workflow,/branches: \[integration\/v0956-main-rooted-rehearsal\]/);
assert.match(workflow,/100000 \+ GITHUB_RUN_NUMBER/,'new builds must get increasing codes');
assert.match(workflow,/GITHUB_RUN_ATTEMPT/,'reruns cannot replace an installed version');
assert.match(workflow,/testkey.pk8/);
assert.match(workflow,/testkey.x509.pem/);
assert.match(workflow,/586c1bd5cf96f9358f36b37ea98fef93f4d0a8e3/,'AOSP private TEST key Git blob hash pinned');
assert.match(workflow,/e242d83e2bf72169ab0abd5280d4d455caef71eb/,'AOSP public certificate Git blob hash pinned');
assert.match(workflow,/git hash-object/);
assert.match(workflow,/openssl pkcs12 -export/);
assert.match(workflow,/srPreviewPackage=true/);
assert.match(workflow,/com\.playereden\.ricochetrumble\.preview/);
assert.match(workflow,/apksigner/);
assert.match(workflow,/actual.*expected/);
assert.match(workflow,/sha256sum/);
assert.match(workflow,/actions\/upload-artifact@v4/);
assert.ok(!workflow.includes('secrets.'),'disposable preview does not require owner secrets');
assert.ok(!workflow.includes('SR_UPLOAD_'),'preview may not use production signing keys');
assert.ok(!/gh release (create|edit|upload)/.test(workflow),'no automatic public release');
assert.match(gradle,/applicationIdSuffix '\.preview'/);
console.log('PASS: automatic source-pinned AOSP development signer, preview-only package, monotonic code, artifact integrity, zero user secrets or public release.');
